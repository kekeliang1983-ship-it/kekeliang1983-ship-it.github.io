/** 全量词库（顺序：仙侠 → 道系 → 治愈 → 可爱，共 108 个） */
export const NAME_POOL: string[] = [...XIANXIA, ...DAO, ...HEALING, ...CUTE];

// 模块级记录上次抽中索引，randomName() 不连抽同一个（仅在数量 >1 时生效）
let lastIndex = -1;

/**
 * 随机赐名：从全量词库均匀随机抽一个，且不与上一次抽中的相同。
 * 返回空串仅在没有可用名字的极端情况下（词库为空），调用方需兜底。
 */
export function randomName(): string {
  const pool = NAME_POOL;
  if (pool.length === 0) return '';
  if (pool.length === 1) return pool[0];
  let i = Math.floor(Math.random() * pool.length);
  while (i === lastIndex) {
    i = Math.floor(Math.random() * pool.length);
  }
  lastIndex = i;
  return pool[i];
}
